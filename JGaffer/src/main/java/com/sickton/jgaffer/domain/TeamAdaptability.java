package com.sickton.jgaffer.domain;

/**
 * Represents how well a team can adapt to tactical changes during a match.
 *
 * <p>Higher adaptability allows the control weight adjustment to scale more effectively,
 * reflecting a team's ability to absorb and execute mid-game tactical shifts.</p>
 *
 * @author sickton
 * @see Team
 */
public enum TeamAdaptability {
    LOW,
    MEDIUM,
    HIGH;
}
